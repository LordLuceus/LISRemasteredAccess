-- Story availability of an interaction object, by the game's own rule: each
-- action carries fact conditions (FactCondAND: every one must match;
-- FactCondOR: at least one must match, when there are any). A condition is a
-- fact name and the state it must be in (bFactActive). The current state comes
-- from the player controller's IsFactActive. An object is available when at
-- least one enabled action's conditions hold.
-- Actor conditions (ActorCondAND/OR) name another object's action and whether
-- it must have run (bTriggered). Each action records that as its own story fact
-- (AutogeneratedFactName, e.g. E1_2A_Toilets_Trolley_Interact01_Triggered), so
-- an actor condition becomes the same fact check: the named object's action's
-- fact name, read from that object. The hammer needs the cart's Interact01 to
-- have run, which is why it appeared too early when these were ignored.
local M={}
-- Pure: does one action's condition list hold? conds: {and={{fact,want}},
-- ["or"]={{fact,want}}}; is_active(fact) -> boolean or nil (unknown).
-- Unknown facts count as matching, so a failed read never hides an object.
function M.action_ok(conds,is_active)
    for _,c in ipairs(conds["and"] or {}) do
        local now=is_active(c.fact)
        if now~=nil and now~=c.want then return false end
    end
    local any=conds["or"] or {}
    if #any==0 then return true end
    for _,c in ipairs(any) do
        local now=is_active(c.fact)
        if now==nil or now==c.want then return true end
    end
    return false
end
-- Reads an action's conditions into plain values (inside the iteration).
-- The story fact recording that `actor`'s action `name` has run.
function M.triggered_fact(actor,name)
    local fact=nil
    pcall(function()
        actor.Actions:ForEach(function(_,v)
            if fact then return end
            local ok,a=pcall(function()return v:get()end)
            if ok then
                local n=nil;pcall(function()n=a.ActionName:ToString()end)
                if n==name then pcall(function()fact=a.AutogeneratedFactName:ToString()end) end
            end
        end)
    end)
    if fact=="" or fact=="None" then return nil end
    return fact
end
function M.read_conditions(action)
    local out={["and"]={},["or"]={}}
    for key,field in pairs({["and"]="FactCondAND",["or"]="FactCondOR"}) do
        pcall(function()
            action[field]:ForEach(function(_,v)
                local ok,c=pcall(function()return v:get()end)
                if ok then
                    local fact,want=nil,nil
                    pcall(function()fact=c.FactName:ToString()end)
                    pcall(function()want=c.bFactActive==true end)
                    if fact and fact~="" and fact~="None" then out[key][#out[key]+1]={fact=fact,want=want} end
                end
            end)
        end)
    end
    -- Actor conditions: copy the target and action name out, resolve afterwards.
    local actor_conds={}
    for key,field in pairs({["and"]="ActorCondAND",["or"]="ActorCondOR"}) do
        pcall(function()
            action[field]:ForEach(function(_,v)
                local ok,c=pcall(function()return v:get()end)
                if ok then
                    local target,name,want=nil,nil,nil
                    pcall(function()target=c.WhatIfInteractionActor end)
                    pcall(function()name=c.ActionName:ToString()end)
                    pcall(function()want=c.bTriggered==true end)
                    if target and name and name~="" and name~="None" then actor_conds[#actor_conds+1]={key=key,target=target,name=name,want=want} end
                end
            end)
        end)
    end
    for _,c in ipairs(actor_conds) do
        local valid=false;pcall(function()valid=c.target:IsValid()end)
        local fact=valid and M.triggered_fact(c.target,c.name) or nil
        if fact then out[c.key][#out[c.key]+1]={fact=fact,want=c.want} end
    end
    return out
end
-- Fact lookup through the controller, cached for one scanner refresh.
function M.fact_reader(controller)
    local cache={}
    return function(fact)
        if cache[fact]~=nil then return cache[fact] end
        local ok,v=pcall(function()return controller:IsFactActive(FName(fact))end)
        local r=nil
        if ok and type(v)=="boolean" then r=v end
        cache[fact]=(r==nil) and "unknown" or r
        return r
    end
end
return M
