-- Real authored gates, replayed through the production scanner collector.
-- Provenance: all-ld/LiS/Content/Maps/Episode02/Sequence03/E2_3A_Junkyard_LD.umap
-- and Episode01/Sequence02/E1_2A_ArtClass_LD.umap (private extracted game data).
-- profile-probe-choice-timer/UE4SS.log:1489-1508 captures camera/pencilcase
-- display=true while Photo_Look01_Triggered=false; bag display=false then.
-- shoot-capture.txt:105-147 independently records the two shooting phases.
-- Positions/labels below are test placeholders; the IDs and action gates are
-- authored data. This checks eligibility, not native rendering or geometry.
package.path='src/?.lua;'..package.path
local n,failed=0,0
local function check(ok,label)
    n=n+1;if not ok then failed=failed+1;print('FAIL scanner story: '..label) end
end
local old_find,old_name,old_flags=FindAllOf,FName,EObjectFlags
local old_source=package.loaded['scanner.sources']
package.loaded['scanner.sources']=nil
local S=require('scanner.sources')
S.translate=function(k)return k end
local errors={}
S.report=function(line)if line:find('error',1,true) then errors[#errors+1]=line end end
local function name(s)return {ToString=function()return s end}end
local function array(values)
    return {ForEach=function(_,fn)for i,value in ipairs(values) do fn(i,{get=function()return value end}) end end}
end
local function action(id,on,facts,actors,generated,shoot)
    local fs,ac={},{}
    for _,f in ipairs(facts or {}) do fs[#fs+1]={FactName=name(f[1]),bFactActive=f[2]} end
    for _,a in ipairs(actors or {}) do ac[#ac+1]={WhatIfInteractionActor=a[1],ActionName=name(a[2]),bTriggered=a[3]} end
    return {ActionName=name(id),bEnabled=on,AutogeneratedFactName=name(generated or 'None'),
        OverrideDisplayName=name(shoot and '$GT_HUD_Action_Shoot' or ''),
        FactCondAND=array(fs),FactCondOR=array({}),ActorCondAND=array(ac),ActorCondOR=array({})}
end
local function actor(level,id)
    return {IsValid=function()return true end,HasAnyFlags=function()return false end,
        bIsRegistered=true,bNeedToHide=false,bHidden=false,bObjectInDisplay=true,
        GetFullName=function()return 'LiSInteractionActor '..level..':PersistentLevel.'..id end,
        GetFName=function()return name(id)end,objectName=name(id),
        K2_GetActorLocation=function()return {X=0,Y=0,Z=0}end}
end
local world,registered,facts='E2_3A',{},{}
local controller={IsValid=function()return true end,GetAddress=function()return 777 end,
    GetWorld=function()return {GetFName=function()return name(world)end}end,
    IsFactActive=function(_,f)return facts[f]==true end}
local component={IsValid=function()return true end,HasAnyFlags=function()return false end,
    GetOwner=function()return controller end,
    RegisteredActors={ForEach=function(_,fn)for i,a in ipairs(registered) do fn(i,{get=function()return a end}) end end}}
FindAllOf=function(class)if class=='LiSInteractionComponent' then return {component} end;return {} end
FName=function(s)return s end
EObjectFlags={RF_BeginDestroyed=1,RF_FinishDestroyed=2}
local function selected()
    local ids={}
    for _,entry in ipairs(S.collect(controller)) do
        if entry.kind=='interaction' then ids[#ids+1]=entry.actor:GetFName():ToString() end
    end
    table.sort(ids);return table.concat(ids,',')
end
local function expected(ids)local copy={table.unpack(ids)};table.sort(copy);return table.concat(copy,',')end
local level='/Game/Maps/Episode02/Sequence03/E2_3A_Junkyard_LD.E2_3A_Junkyard_LD'
local first={'LiSInteractionActor_Wheel_8','LiSInteractionActor_Barrel_7','LiSInteractionActor_Monitor_9','LiSInteractionActor_Shelf_3'}
local second={'LiSInteractionActor_Bumper_13','LiSInteractionActor_Tank_11','LiSInteractionActor_Tire_16','LiSInteractionActor_Windshield_15'}
for phase,ids in ipairs({first,second}) do
    local fact=phase==1 and 'Enable_InteractionGun03' or 'Enable_InteractionGun04'
    for _,id in ipairs(ids) do
        local a=actor(level,id)
        a.Actions=array({action('Look01',false,{{fact,true}}),
            action('Interact01',true,{{fact,true}},nil,nil,true),action('Interact02',false)})
        registered[#registered+1]=a
    end
end
check(selected()=='','neither set appears before shooting despite display=true')
facts.Enable_InteractionGun03=true
check(selected()==expected(first),'first aiming phase lists exactly its four targets')
facts.Enable_InteractionGun03=false;facts.Enable_InteractionGun04=true
check(selected()==expected(second),'second aiming phase replaces, not adds to, the first set')
facts.Enable_InteractionGun04=false
check(selected()=='','both sets disappear when shooting ends, including remembered entries')
facts.Enable_InteractionGun03=true
check(selected()==expected(first),'rewinding to the first phase restores only its targets')

world='E1_2A';facts={};registered={}
level='/Game/Maps/Episode01/Sequence02/E1_2A_ArtClass_LD.E1_2A_ArtClass_LD'
local rewind='E1_2A_REWINDED'
local disabled='E1_2A_ArtClass_LD_DisableInteractions'
local photo_fact='E1_2A_ArtClass_Photo_Look01_Triggered'
local selfie_fact='E1_2A_ArtClass_Polaroid_Interact01_Triggered'
local photo=actor(level,'LiSInteractionActor_PhotoBook_7')
photo.Actions=array({action('Look01',true,nil,nil,photo_fact)})
for _,id in ipairs({'LiSInteractionActor_PencilCase_8','LiSInteractionActor_MaxBag_3'}) do
    local a=actor(level,id)
    a.Actions=array({action('Look01',true,{{rewind,false}},{{photo,'Look01',true}}),
        action('Look02',true,{{rewind,true},{disabled,false}}),action('Interact01',false)})
    registered[#registered+1]=a
end
local camera=actor(level,'LiSInteractionActor_Polaroid_1')
camera.Actions=array({
    action('Look01',true,{{disabled,false},{rewind,false}},{{photo,'Look01',true},{camera,'Interact01',false}}),
    action('Interact01',true,{{rewind,false},{disabled,false}},{{photo,'Look01',true}},selfie_fact),
    action('Interact02',true,{{rewind,true},{disabled,false}}),
    action('Look02',true,{{rewind,true},{disabled,false}}),
    action('Look03',true,{{rewind,false},{disabled,false}},{{camera,'Interact01',true}})})
registered[#registered+1]=camera
registered[2].bObjectInDisplay=false -- exact historical classroom capture
check(selected()=='','captured display=true camera/pencilcase stay gated before looking at the photo')
registered[2].bObjectInDisplay=true
check(selected()=='','showing the bag too must not waive its photo prerequisite')
facts[photo_fact]=true
local desk={'LiSInteractionActor_PencilCase_8','LiSInteractionActor_MaxBag_3','LiSInteractionActor_Polaroid_1'}
check(selected()==expected(desk),'looking at the photo releases all three desk objects')
facts[photo_fact]=false
check(selected()=='','reversing the photo trigger hides even remembered desk objects')
facts[selfie_fact]=true
check(selected()==expected({desk[3]}),'camera Look03 follows its own selfie trigger, not an invented universal photo gate')
facts[selfie_fact]=false;facts[rewind]=true
check(selected()==expected(desk),'native post-rewind alternatives work without the initial photo trigger')
facts[disabled]=true
check(selected()=='','post-rewind interaction lock still hides all three')
check(#errors==0,'collector does not swallow an exception: '..table.concat(errors,'; '))
FindAllOf,FName,EObjectFlags=old_find,old_name,old_flags
package.loaded['scanner.sources']=old_source
print('Scanner story gates: '..n..' checks, '..failed..' failures')
assert(failed==0,'scanner story-gate regressions')
return n
