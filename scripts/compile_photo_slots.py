"""Validate and deterministically compile authored native photo-slot identities."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'descriptions/journal_photo_slots.json'
OUTPUT = ROOT / 'src/hud/journal_photo_slots.lua'
PATH = re.compile(r'^/Game/[A-Za-z0-9_/-]+\.[A-Za-z0-9_-]+$')


def validate(rows):
    if not isinstance(rows, list) or len(rows) != 50:
        raise ValueError('expected 50 photo slots')
    identities, resources = set(), set()
    for row in rows:
        if not isinstance(row, dict) or set(row) != {'episode', 'index', 'locked', 'unlocked'}:
            raise ValueError('invalid slot fields')
        episode, index = row['episode'], row['index']
        if episode not in [f'Episode{i}' for i in range(1, 6)]:
            raise ValueError('invalid episode')
        if type(index) is not int or not 0 <= index < 10:
            raise ValueError('invalid zero-based index')
        key = (episode, index)
        if key in identities:
            raise ValueError('duplicate episode/index')
        identities.add(key)
        for state in ('locked', 'unlocked'):
            path = row[state]
            if (not isinstance(path, str) or len(path) > 2048 or not PATH.fullmatch(path)
                    or '//' in path or '/.' in path):
                raise ValueError('invalid full resource path')
            canonical = path.lower()
            if canonical in resources:
                raise ValueError('duplicate or colliding resource')
            resources.add(canonical)
    expected = [(f'Episode{ep}', i) for ep in range(1, 6) for i in range(10)]
    if [(r['episode'], r['index']) for r in rows] != expected:
        raise ValueError('slots must retain episode/native child index order')
    return rows


def render(rows):
    validate(rows)
    lines = ['-- Generated by scripts/compile_photo_slots.py; do not edit.',
             '-- Native zero-based child order; identities only, no artwork or captions.', 'return {']
    for row in rows:
        lines.append('    {episode=%s,index=%d,locked=%s,unlocked=%s},' % (
            json.dumps(row['episode']), row['index'], json.dumps(row['locked']), json.dumps(row['unlocked'])))
    return '\n'.join(lines + ['}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--import-manifest', type=Path,
                        help='explicit offline import of verified extraction manifest (no assets copied)')
    args = parser.parse_args()
    if args.import_manifest:
        if args.check:
            parser.error('--check cannot import metadata')
        manifest = json.loads(args.import_manifest.read_text(encoding='utf-8'))
        rows = [{'episode': r['episode_name'], 'index': r['index'],
                 'locked': r['states']['locked']['object_path'],
                 'unlocked': r['states']['unlocked']['object_path']} for r in manifest['rows']]
        validate(rows)
        SOURCE.write_text(json.dumps(rows, indent=2) + '\n', encoding='utf-8', newline='\n')
    rows = json.loads(SOURCE.read_text(encoding='utf-8'))
    result = render(rows)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != result.encode('utf-8'):
            parser.exit(1, 'photo-slot catalogue is stale; run scripts/compile_photo_slots.py\n')
    else:
        OUTPUT.write_text(result, encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
