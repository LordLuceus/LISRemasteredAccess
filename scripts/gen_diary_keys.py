"""Regenerates src/hud/diary_keys.lua from the game's English Menus.ini [Diary]
section (unpacked under artifacts/loc). The keys are the same in every language."""
import re
from pathlib import Path
root=Path(__file__).resolve().parent.parent
f=(root/'artifacts/loc/LIS/Content/Packages/Localization/en/Menus.ini').read_text(encoding='utf-8-sig')
sec='';keys=[]
for line in f.splitlines():
    m=re.match(r'^\[(.+)\]',line)
    if m: sec=m.group(1);continue
    # Diary pages (E1_Page05_C, a few spelled E1_page...) and character pages
    # (Chara_Kate_A): both are shown as paragraph elements.
    m=re.match(r'^(E\d_[Pp]age\d+_[A-Za-z]+|Chara_[A-Za-z0-9]+_[A-Za-z]+)=',line)
    if sec=='Diary' and m: keys.append(m.group(1))
out='-- Authored journal paragraph keys (diary and character pages) ($GT_Menus_Diary_<key>), from the game\'s\n-- Menus.ini [Diary] section. Generated by scripts/gen_diary_keys.py.\nreturn {\n'+''.join(f'    "{k}",\n' for k in keys)+'}\n'
(root/'src/hud/diary_keys.lua').write_text(out,encoding='utf-8',newline='\n')
print(len(keys),'keys')
