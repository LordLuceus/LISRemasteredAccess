"""Validate reviewed caption data and compile the runtime Lua catalogue.

Only authored prose, asset IDs and source hashes ship. Private PNGs and draft
transcriptions never enter the runtime file. Optional --inventory verifies actual
exported PNG hashes and writes a coverage receipt; folder coverage is not proof
of complete in-game coverage.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

FIELDS = ('asset', 'language', 'text', 'image_sha256', 'status')
ASSET = re.compile(r'/Game/[\w/-]+\.[\w-]+', re.ASCII | re.IGNORECASE)
LANGUAGE = re.compile(r'[a-z]{2,3}(?:[-_][a-zA-Z]+)?', re.ASCII)


def validate(records):
    if not isinstance(records, list) or not records:
        raise ValueError('Expected a nonempty list of reviewed captions')
    seen = set()
    result = []
    for record in records:
        if not isinstance(record, dict) or set(record) != set(FIELDS):
            raise ValueError('Runtime records must contain only caption fields')
        if not all(isinstance(record[k], str) for k in FIELDS):
            raise ValueError('Caption fields must be strings')
        asset = record['asset']
        if not ASSET.fullmatch(asset) or '//' in asset or '/.' in asset:
            raise ValueError('Invalid full texture object path: ' + asset)
        if not LANGUAGE.fullmatch(record['language']):
            raise ValueError('Invalid caption language')
        if record['status'] != 'reviewed':
            raise ValueError('Draft captions cannot be published')
        if not record['text'].strip() or any(ord(c) < 32 for c in record['text']):
            raise ValueError('Caption must be nonempty single-line prose')
        if not re.fullmatch('[0-9a-f]{64}', record['image_sha256']):
            raise ValueError('Invalid source image hash')
        language = record['language'].lower().replace('_', '-')
        key = (asset.lower(), language)
        if key in seen:
            raise ValueError('Duplicate caption: ' + asset)
        seen.add(key)
        result.append(dict(record, language=language))
    return sorted(result, key=lambda r: (r['asset'].lower(), r['language']))


def lua_string(value):
    # Non-ASCII prose remains UTF-8; JSON's \u escapes are not Lua escapes.
    return '"' + value.replace('\\', '\\\\').replace('"', '\\"') + '"'


def render(records):
    records = validate(records)
    lines = ['-- Generated by scripts/compile_descriptions.py; edit descriptions/episode1.en.json.',
             '-- Authored captions only: no extracted images or unreviewed transcriptions.', 'return {']
    for record in records:
        lines.append('    {')
        for field in FIELDS:
            lines.append('        ' + field + '=' + lua_string(record[field]) + ',')
        lines.append('    },')
    return '\n'.join(lines + ['}', ''])


def coverage(records, inventory):
    records = validate(records)
    manifest = json.loads(inventory.read_text(encoding='utf-8'))
    assets = {r['object_path'].lower(): r for r in manifest['assets'] if r['status'] == 'decoded'}
    verified = set()
    for record in records:
        asset = assets.get(record['asset'].lower())
        if not asset:
            raise ValueError('Caption asset absent from inventory: ' + record['asset'])
        png = (inventory.parent / asset['png']).resolve()
        if not png.is_relative_to(inventory.parent.resolve()):
            raise ValueError('Image path escapes inventory')
        actual = hashlib.sha256(png.read_bytes()).hexdigest()
        if actual != record['image_sha256'] or actual != asset['png_sha256']:
            raise ValueError('Source image hash mismatch: ' + record['asset'])
        verified.add(record['asset'].lower())
    return {'scope': manifest['scope'], 'runtime_coverage': 'not established',
            'assets': len(assets), 'described_assets': len(verified),
            'distinct_images': len({a['png_sha256'] for a in assets.values()}),
            'described_images': len({assets[a]['png_sha256'] for a in verified}),
            'missing_assets': sorted(a['object_path'] for k, a in assets.items() if k not in verified)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--records', type=Path, default=Path('descriptions/episode1.en.json'))
    parser.add_argument('--output', type=Path, default=Path('src/descriptions/data.lua'))
    parser.add_argument('--inventory', type=Path)
    parser.add_argument('--coverage', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    records = json.loads(args.records.read_text(encoding='utf-8'))
    output = render(records)
    report = coverage(records, args.inventory) if args.inventory else None
    if args.coverage and report is None:
        parser.error('--coverage requires --inventory')
    if args.check:
        if not args.output.exists() or args.output.read_bytes() != output.encode('utf-8'):
            raise ValueError('Generated runtime catalogue is stale: ' + str(args.output))
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(output.encode('utf-8'))
    if args.coverage:
        args.coverage.write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print('Reviewed captions: ' + str(len(records)))
    if report:
        print('Export coverage: {described_assets}/{assets} assets; {described_images}/{distinct_images} images; runtime coverage unproven'.format(**report))


if __name__ == '__main__':
    main()
